#!/usr/bin/env python3
"""Make a form's .resx usable on Linux, so upstream's InitializeComponent runs unchanged.

Upstream designer code loads some values through ComponentResourceManager
(resources.GetObject("$this.Icon"), resources.GetString(...)). The .resx stores
images as System.Drawing types, which .NET on Linux can't build or load. This
writes a ULDB .resx with just the entries the designer reads:
  - strings: copied
  - file references (icons, bitmaps): pointed at the same files, typed as
    ULDB.Compat's System.Drawing.Bitmap/Icon
  - inline images (PNG bytes): written next to the output and referenced
The project compiles it with GenerateResourceUsePreserializedResources, so at
runtime Bitmap/Icon are created from a stream (System.Resources.Extensions).

Usage: formresx.py DESIGNER_CS RESX OUT_RESX
"""

import base64
import os
import re
import sys
from xml.sax.saxutils import escape

COMPAT_TYPES = {"System.Drawing.Bitmap": "System.Drawing.Bitmap, ULDB.Compat",
                "System.Drawing.Icon": "System.Drawing.Icon, ULDB.Compat",
                "System.Drawing.Image": "System.Drawing.Bitmap, ULDB.Compat"}

HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/resxgen/formresx.py from upstream {source}. Do not edit. -->
<root>
  <resheader name="resmimetype"><value>text/microsoft-resx</value></resheader>
  <resheader name="version"><value>2.0</value></resheader>
  <resheader name="reader"><value>System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>
  <resheader name="writer"><value>System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>
"""


def compat_type(typename):
    name = typename.split(",")[0].strip()
    if name not in COMPAT_TYPES:
        sys.exit("formresx: unsupported resource type " + typename)
    return COMPAT_TYPES[name]


def main():
    designer, resx, out = sys.argv[1:4]
    with open(designer, encoding="utf-8-sig") as f:
        code = f.read()
    with open(resx, encoding="utf-8-sig") as f:
        text = f.read()

    wanted = sorted(set(re.findall(r'resources\.Get(?:String|Object)\("([^"]+)"\)', code)))
    outdir = os.path.dirname(os.path.abspath(out))
    stem = os.path.splitext(os.path.basename(out))[0]
    entries = []
    for name in wanted:
        m = re.search(r'<data name="' + re.escape(name) + r'"([^>]*)>\s*<value>(.*?)</value>', text, re.S)
        if not m:
            sys.exit("formresx: " + name + " not found in " + resx)
        attrs, value = m.group(1), m.group(2)
        typ = re.search(r'type="([^"]+)"', attrs)
        mime = re.search(r'mimetype="([^"]+)"', attrs)
        if typ is None:
            entries.append('  <data name="%s" xml:space="preserve"><value>%s</value></data>' % (escape(name), value))
        elif typ.group(1).startswith("System.Resources.ResXFileRef"):
            path, reftype = value.split(";")[0:2]
            path = os.path.normpath(os.path.join(os.path.dirname(resx), path.replace("\\", "/")))
            rel = os.path.relpath(path, outdir)
            entries.append('  <data name="%s" type="System.Resources.ResXFileRef, System.Windows.Forms"><value>%s;%s</value></data>'
                           % (escape(name), escape(rel), compat_type(reftype)))
        elif mime and mime.group(1) == "application/x-microsoft.net.object.bytearray.base64":
            data = base64.b64decode("".join(value.split()))
            if not data.startswith(b"\x89PNG"):
                sys.exit("formresx: " + name + " isn't PNG data")
            filename = stem + "." + re.sub(r"[^A-Za-z0-9_.-]", "_", name) + ".png"
            with open(os.path.join(outdir, filename), "wb") as f:
                f.write(data)
            entries.append('  <data name="%s" type="System.Resources.ResXFileRef, System.Windows.Forms"><value>%s;%s</value></data>'
                           % (escape(name), filename, compat_type(typ.group(1))))
        else:
            sys.exit("formresx: unsupported entry " + name + " (" + attrs.strip() + ")")

    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER.format(source=os.path.relpath(resx).replace("\\", "/")))
        f.write("\n".join(entries) + "\n</root>\n")
    print(os.path.basename(out) + ": " + str(len(entries)) + " entries")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Generate ULDB's replacement for an upstream Properties/Resources.Designer.cs.

Upstream stores images in .resx files that .NET deserializes into WinForms-era
System.Drawing objects, which doesn't work on Linux. This reads the .resx and the
matching Designer.cs, and writes:
  - a C# class with the same name and properties that loads each file from an
    embedded resource (using ULDB.Compat's System.Drawing types)
  - an MSBuild items file that embeds those files

Usage: resxgen.py RESX DESIGNER_CS OUT_CS OUT_PROPS NAMESPACE CLASSNAME
"""

import os
import re
import sys


def main():
    resx, designer, out_cs, out_props, namespace, classname = sys.argv[1:7]
    with open(resx, encoding="utf-8-sig") as f:
        resx_text = f.read()
    with open(designer, encoding="utf-8-sig") as f:
        designer_text = f.read()

    # Only properties upstream's generated class actually exposes (the .resx has samples too).
    wanted = {n: t for t, n in re.findall(r"internal static ([\w.\[\]]+) (\w+) \{", designer_text)}
    wanted.pop("ResourceManager", None)
    wanted.pop("Culture", None)

    entries = []
    for name, value in re.findall(r'<data name="([^"]+)" type="System\.Resources\.ResXFileRef[^"]*">\s*<value>([^<]+)</value>', resx_text):
        if name not in wanted:
            continue
        path, typename = value.split(";")[0:2]
        path = os.path.normpath(os.path.join(os.path.dirname(resx), path.replace("\\", "/")))
        entries.append((name, path, typename.split(",")[0].strip(), wanted[name]))

    missing = sorted(set(wanted) - {e[0] for e in entries})
    if missing:
        sys.exit("resx entries not handled: " + ", ".join(missing))

    logical_prefix = "ULDB.Resources." + namespace + "." + classname + "."
    lines = [
        "// <auto-generated>",
        "// ULDB replacement for upstream " + os.path.relpath(designer).replace("\\", "/") + ",",
        "// generated by tools/resxgen/resxgen.py. Loads the same files from embedded resources",
        "// instead of .resx-serialized WinForms objects. Do not edit.",
        "// </auto-generated>",
        "",
        "using System.Drawing;",
        "using System.IO;",
        "",
        "namespace " + namespace,
        "{",
        "\tinternal static class " + classname,
        "\t{",
        "\t\tprivate static Stream Open(string name)",
        "\t\t{",
        "\t\t\tStream s = typeof(" + classname + ").Assembly.GetManifestResourceStream(\"" + logical_prefix + "\" + name);",
        "\t\t\tif(s == null) throw new FileNotFoundException(\"Missing embedded resource " + logical_prefix + "\" + name);",
        "\t\t\treturn s;",
        "\t\t}",
        "",
    ]
    for name, path, typename, proptype in sorted(entries):
        if typename == "System.Drawing.Bitmap":
            body = "using(Stream s = Open(\"" + name + "\")) return new Bitmap(s);"
        elif typename == "System.Drawing.Icon":
            body = "using(Stream s = Open(\"" + name + "\")) return new Icon(s);"
        elif typename == "System.Byte[]":
            body = "using(Stream s = Open(\"" + name + "\")) using(MemoryStream ms = new MemoryStream()) { s.CopyTo(ms); return ms.ToArray(); }"
        elif typename == "System.String":
            body = "using(Stream s = Open(\"" + name + "\")) using(StreamReader r = new StreamReader(s)) return r.ReadToEnd();"
        else:
            sys.exit("unsupported resource type " + typename + " for " + name)
        # Upstream returns a new object on every access too (ResourceManager.GetObject).
        lines.append("\t\tinternal static " + proptype + " " + name + " { get { " + body + " } }")
    lines += ["\t}", "}", ""]
    with open(out_cs, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    items = ['<Project>', '  <!-- Generated by tools/resxgen/resxgen.py -->', '  <ItemGroup>']
    for name, path, typename, proptype in sorted(entries):
        rel = os.path.relpath(path, os.path.dirname(out_props)).replace("\\", "/")
        items.append('    <EmbeddedResource Include="$(MSBuildThisFileDirectory)' + rel + '" LogicalName="' + logical_prefix + name + '" />')
    items += ['  </ItemGroup>', '</Project>', '']
    with open(out_props, "w", encoding="utf-8") as f:
        f.write("\n".join(items))
    print(f"{classname}: {len(entries)} resources")


if __name__ == "__main__":
    main()

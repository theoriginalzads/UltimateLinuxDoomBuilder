// Emits C# source for public enums from a reference assembly, with exact values.
using System.Reflection;
using System.Reflection.Metadata;
using System.Reflection.PortableExecutable;
using System.Text;
var path = args[0]; var wanted = args.Skip(1).ToHashSet();
using var fs = File.OpenRead(path); using var pe = new PEReader(fs); var md = pe.GetMetadataReader();
var byNs = new SortedDictionary<string, StringBuilder>();
foreach (var h in md.TypeDefinitions) {
  var t = md.GetTypeDefinition(h);
  if ((t.Attributes & TypeAttributes.VisibilityMask) != TypeAttributes.Public) continue;
  var name = md.GetString(t.Name); var ns = md.GetString(t.Namespace);
  if (!wanted.Contains(name)) continue;
  bool flags = t.GetCustomAttributes().Any(a => AttrName(md, md.GetCustomAttribute(a)) == "FlagsAttribute");
  string underlying = "int"; var sb = new StringBuilder();
  foreach (var fh in t.GetFields()) {
    var f = md.GetFieldDefinition(fh); var fname = md.GetString(f.Name);
    if (fname == "value__") { var sig = md.GetBlobReader(f.Signature); sig.ReadByte(); var code = sig.ReadSignatureTypeCode();
      underlying = code switch { SignatureTypeCode.Byte=>"byte", SignatureTypeCode.UInt32=>"uint", SignatureTypeCode.Int64=>"long", SignatureTypeCode.Int16=>"short", _=>"int" }; continue; }
    var ch = f.GetDefaultValue(); if (ch.IsNil) continue; var c = md.GetConstant(ch); var br = md.GetBlobReader(c.Value);
    object v = c.TypeCode switch { ConstantTypeCode.Int32=>br.ReadInt32(), ConstantTypeCode.UInt32=>br.ReadUInt32(), ConstantTypeCode.Byte=>br.ReadByte(), ConstantTypeCode.Int16=>br.ReadInt16(), ConstantTypeCode.Int64=>br.ReadInt64(), _=>br.ReadInt32() };
    sb.AppendLine($"\t\t{fname} = {(underlying=="uint" ? $"unchecked((uint){v})" : v)},");
  }
  if (!byNs.TryGetValue(ns, out var nsb)) byNs[ns] = nsb = new StringBuilder();
  if (flags) nsb.AppendLine("\t[Flags]");
  nsb.AppendLine($"\tpublic enum {name}" + (underlying=="int" ? "" : " : " + underlying));
  nsb.AppendLine("\t{"); nsb.Append(sb); nsb.AppendLine("\t}"); nsb.AppendLine();
}
Console.WriteLine("// <auto-generated>\n// Enum values extracted from the .NET Framework reference assemblies so stored\n// values (e.g. keyboard shortcuts in settings) stay compatible with upstream UDB.\n// </auto-generated>\n\nusing System;\n");
foreach (var (ns, nsb) in byNs) { Console.WriteLine($"namespace {ns}\n{{"); Console.Write(nsb.ToString().TrimEnd() + "\n"); Console.WriteLine("}\n"); }
static string AttrName(MetadataReader md, CustomAttribute a) {
  if (a.Constructor.Kind == HandleKind.MemberReference) { var mr = md.GetMemberReference((MemberReferenceHandle)a.Constructor);
    if (mr.Parent.Kind == HandleKind.TypeReference) return md.GetString(md.GetTypeReference((TypeReferenceHandle)mr.Parent).Name); }
  return "";
}
